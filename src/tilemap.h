#define MAP_W 25
#define MAP_H 19
#define TILE 32.0f

enum Square {
    BLANK,
    WALL,
    VISIBLE
};

typedef struct
{
    int x,y;
} TileCoord;


int originalMap[MAP_H][MAP_W];
int mapGrid[MAP_H][MAP_W];
int visibleGrid[MAP_H][MAP_W] = ORIGINAL_VISIBILITY;
int originalVisibleGrid[MAP_H][MAP_W] = ORIGINAL_VISIBILITY;




static inline bool isWall(int col, int row){
    if(col<0 || col >= MAP_W || row <0||row>=MAP_H) return true;
    return mapGrid[row][col]==1;
}

static inline bool isLit(int col, int row){
    if(col<0 || col >= MAP_W || row <0||row>=MAP_H) return false;
    return mapGrid[row][col]==2;
}


static inline bool rectHitsWall(float x, float y, float w, float h){
    int left = (int)(x/TILE);
    int right = (int)((x+w-.0001)/TILE);
    int top = (int)(y/TILE);
    int bottom = (int)((y+h-.0001)/TILE);

    for (int r = top; r <= bottom; r++)
        for (int c = left; c <= right; c++){
            if (isWall(c, r)){
                return true;
            }
        }
    return false;
}

static inline void renderTilemap(SDL_Renderer *renderer) {
    for (int r = 0; r < MAP_H; r++) {
        for (int c = 0; c < MAP_W; c++) {
            SDL_FRect rect = { c * TILE, r * TILE, TILE, TILE };
            

            int drawBrightness = 50;

            if(visibleGrid[r][c]){
                switch(mapGrid[r][c]){
                    case WALL:
                        drawBrightness = 50;
                    break;
                    case BLANK:
                        drawBrightness = 100;
                    break;
                    case VISIBLE:
                        drawBrightness = 180;
                    break;
                }
            }

            SDL_SetRenderDrawColor(renderer, drawBrightness,drawBrightness,drawBrightness, 255);
            SDL_RenderFillRect(renderer, &rect);
            
        }
    }
}